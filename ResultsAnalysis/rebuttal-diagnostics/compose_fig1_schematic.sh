#!/usr/bin/env bash
# Composes the revised Fig. 1 (Bayesian-ARGOS schematic): the submitted drawing
# schematic-plots/algorithm-description.pdf (diagrams.net export, one page of
# 1025.04 x 1008.96 pt) with the three diagnostic insets of panel e replaced by
# the house-style insets drawn by fig1_insets.R.  A standalone TikZ document
# places the page with \includegraphics, covers the interior of each of the
# three pink-framed boxes of panel e with a white rounded rectangle (the frames
# stay), writes the new title in Helvetica at the size of the old box titles
# (14 pt on the page, measured from the cap height of "Residual analysis") and
# places the inset scaled to 186 pt, the width the box offers.
#
# Geometry (pt, origin bottom left), measured from a 144 dpi and a 600 dpi
# rasterisation of the page (see the report in the manuscript repository):
#   frames (outer edges): x 332.5-527.5, 533.5-728.5, 735.0-930.0; y 28.5-251.0;
#   frame 1 pt thick, outer corner radius 3 pt; old titles at baseline y = 234,
#   first glyph origin 4.7-6.7 pt right of the frame.
# The generated TeX file is kept beside this script (compose_fig1_schematic.tex).
#
# Usage: bash compose_fig1_schematic.sh      (pdflatex, about 2 s)
# Writes <manuscript>/imgs/bayesian_argos_schematic.pdf and a copy in
# figures/bayesian_argos_schematic.pdf.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MR="${ARGOS_MANUSCRIPT_DIR:-$(cd "$HERE/../../../.." && pwd)}"
PAGE="$MR/schematic-plots/algorithm-description.pdf"
INSETS="$HERE/figures"
OUT_NAME="bayesian_argos_schematic"
BUILD="${TMPDIR:-/tmp}/compose_fig1_$$"
mkdir -p "$BUILD"
for f in "$PAGE" "$INSETS/fig1_inset_residuals.pdf" "$INSETS/fig1_inset_khat.pdf" "$INSETS/fig1_inset_vif.pdf"; do
  [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
done

# box geometry: left edge of the frame (outer), centre x, and the common y values
BOX_LEFT=(332.5 533.5 735.0); BOX_CX=(430.0 631.0 832.5)
TITLES=("Residual analysis" "Influential observations" "Multicollinearity")
FILES=("fig1_inset_residuals.pdf" "fig1_inset_khat.pdf" "fig1_inset_vif.pdf")
INSET_W=186          # pt on the page (box interior is 193 pt wide)
INSET_TOP=218.6      # top edge of the inset: centred between the title and the bottom of the box
TITLE_BASE=234.0     # baseline of the box titles
TITLE_DX=5.0         # text origin right of the outer left edge of the frame

TEX="$HERE/compose_fig1_schematic.tex"
{
  echo '% Generated by compose_fig1_schematic.sh; do not edit by hand.'
  echo '\documentclass[border=0pt]{standalone}'
  echo '\usepackage[T1]{fontenc}'
  echo '\usepackage{helvet}'
  echo '\renewcommand{\familydefault}{\sfdefault}'
  echo '\usepackage{tikz,graphicx}'
  echo '\begin{document}'
  echo '\begin{tikzpicture}[x=1pt,y=1pt,inner sep=0pt,outer sep=0pt]'
  echo "\\node[anchor=south west] at (0,0) {\\includegraphics{$PAGE}};"
  for i in 0 1 2; do
    L=${BOX_LEFT[$i]}; CX=${BOX_CX[$i]}
    X0=$(python3 -c "print($L + 1.1)"); X1=$(python3 -c "print($L + 195.0 - 1.1)")
    TX=$(python3 -c "print($L + $TITLE_DX)")
    echo "\\fill[white,rounded corners=2pt] ($X0,29.6) rectangle ($X1,249.9);"
    echo "\\node[anchor=base west,font=\\fontsize{14}{16}\\selectfont] at ($TX,$TITLE_BASE) {${TITLES[$i]}};"
    echo "\\node[anchor=north] at ($CX,$INSET_TOP) {\\includegraphics[width=${INSET_W}pt]{$INSETS/${FILES[$i]}}};"
  done
  echo '\end{tikzpicture}'
  echo '\end{document}'
} > "$TEX"

cp "$TEX" "$BUILD/$OUT_NAME.tex"
( cd "$BUILD" && pdflatex -interaction=nonstopmode -halt-on-error "$OUT_NAME.tex" > "$BUILD/pdflatex.log" 2>&1 ) || { tail -30 "$BUILD/pdflatex.log"; exit 1; }
mkdir -p "$MR/imgs" "$INSETS"
cp "$BUILD/$OUT_NAME.pdf" "$INSETS/$OUT_NAME.pdf"
cp "$BUILD/$OUT_NAME.pdf" "$MR/imgs/$OUT_NAME.pdf"
rm -rf "$BUILD"
echo "wrote $MR/imgs/$OUT_NAME.pdf"
pdfinfo "$MR/imgs/$OUT_NAME.pdf" | grep "Page size"
